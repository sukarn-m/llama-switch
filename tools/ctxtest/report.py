#!/usr/bin/env python3
"""Build results/SUMMARY.md from the saved result files.

  report.py [--all]

One row per model, from the latest production run of each test (a run is
"production" when launch.py started the model exactly as config.yaml says;
runs with overrides are variants and only appear with --all). Below the
table, each model gets its quiz grade notes and a list of every result file,
so older runs stay findable. The JSON files are the record; this file is
generated and safe to rebuild at any time.
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import RESULTS  # noqa: E402

COLUMNS = ["Model", "Engine", "Gen t/s (short)", "Draft accept", "PP t/s @~30k",
           "Stress: tokens", "PP t/s avg", "Gen t/s @max", "Min free GPU0/GPU1 MiB", "Recall",
           "OCR CER", "OCR fields", "OCR s", "Quiz", "Fabrications"]


def load(include_variants):
    runs = []
    for path in sorted(glob.glob(os.path.join(RESULTS, "*", "*.json"))):
        try:
            doc = json.load(open(path, encoding="utf-8"))
        except Exception as e:
            print("skip", path, e, file=sys.stderr)
            continue
        if doc.get("schema") != 1:
            continue
        doc["_path"] = os.path.relpath(path, RESULTS)
        if include_variants or doc.get("production"):
            runs.append(doc)
    return runs


def kind(doc):
    if doc["test"] == "needle":
        return "needle:" + (doc["params"].get("tag") or "untagged")
    if doc["test"] == "quiz":
        return "quiz:" + doc["params"]["quiz_version"]
    return doc["test"]


def fmt(v, spec=""):
    return "–" if v is None else format(v, spec)


def main():
    include_variants = "--all" in sys.argv
    runs = load(include_variants)
    latest = {}
    for d in runs:  # sorted by path, so later timestamps win
        key = (d["model"] + (f" ({d['variant']})" if d.get("variant") else ""), kind(d))
        latest[key] = d
    models = sorted({k[0] for k in latest})
    quiz_versions = sorted({k[1] for k in latest if k[1].startswith("quiz:")})

    out = ["# Model test results", "",
           "Generated by `tools/ctxtest/report.py` from the JSON files in this directory; do not edit by hand.",
           "Each row uses the latest production run of each test. Quiz: graded score / max "
           f"({', '.join(v.split(':')[1] for v in quiz_versions) or 'no quiz yet'}), 2 per answer; "
           "Fabrications counts answers with invented law, case law or changed facts.",
           "OCR: character error rate on the rendered Hindi deed page (lower is better) and key fields found.",
           "", "| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    for m in models:
        g = lambda k: latest.get((m, k))  # noqa: E731
        bench, pp, stress, ocr = g("bench"), g("needle:pp30k"), g("needle:stress"), g("ocr")
        quiz = next((g(v) for v in reversed(quiz_versions) if g(v)), None)
        any_run = bench or pp or stress or ocr or quiz
        eng = any_run["run"]["engine"].split("|")[0].replace("version: ", "").strip() if any_run else ""
        if any_run and "llama.cpp-inkling" in any_run["run"]["binary"]:
            eng += " (patched)"
        bm, pm, sm, om = [(x or {}).get("metrics", {}) for x in (bench, pp, stress, ocr)]
        qm = (quiz or {}).get("metrics", {})
        free = sm.get("min_free_mib")
        quiz_s = (f"{qm['score']}/{qm['score_max']}" if qm.get("graded") else ("ungraded" if quiz else None))
        row = [m, eng, fmt(bm.get("gen_tps_mean"), ".1f"), fmt(bm.get("draft_accept_rate"), ".2f"),
               fmt(pm.get("pp_tps"), ".0f"), fmt(sm.get("prompt_tokens")), fmt(sm.get("pp_tps"), ".0f"),
               fmt(sm.get("gen_tps"), ".1f"), "/".join(map(str, free)) if free else "–", fmt(sm.get("recall")),
               fmt(om.get("cer"), ".3f"),
               f"{om['fields_found']}/{om['fields_total']}" if om else "–", fmt(om.get("wall_s"), ".1f"),
               fmt(quiz_s), fmt(qm.get("fabrications") if qm.get("graded") else None)]
        out.append("| " + " | ".join(row) + " |")

    out += ["", "## Per model", ""]
    for m in models:
        out += [f"### {m}", ""]
        quiz = next((latest.get((m, v)) for v in reversed(quiz_versions) if latest.get((m, v))), None)
        if quiz and quiz["data"].get("grades"):
            out.append(f"Quiz notes ({quiz['params']['quiz_version']}, {quiz['timestamp'][:10]}):")
            out.append("")
            for gr in quiz["data"]["grades"]:
                mark = f"{gr.get('score', '?')}{' **fabricated**' if gr.get('fabricated') else ''}"
                note = f" – {gr['note']}" if gr.get("note") else ""
                out.append(f"- {gr['q']}/{gr['sample']}: {mark}{note}")
            out.append("")
        base = m.split(" (")[0]
        files = [d for d in runs if d["model"] == base and (d.get("variant") or None) == (m[len(base) + 2:-1] or None)]
        out.append("Runs: " + ", ".join(f"[{kind(d)} {d['timestamp'][:16]}]({d['_path']})" for d in files))
        out.append("")

    path = os.path.join(RESULTS, "SUMMARY.md")
    os.makedirs(RESULTS, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path, f"({len(models)} models, {len(runs)} runs)")


if __name__ == "__main__":
    main()
